#!/usr/bin/env python3
"""Upload every GLB in a folder through win/upload_model_skyrally.ps1 (Open Cloud upload with a validated Use grant to the
universe; the key never leaves the PC), recording ids in <folder>/uploaded.json, and optionally emit a generated Luau id table.
Idempotent by sha256: a file whose bytes were already uploaded is skipped.
Usage: upload_models.py <folder> <name_prefix> [<luau_out> <TableName>] [--only=a,b] [--nested]
--nested: one sub-folder per asset holding <name>/<name>.glb (the Tripo pipeline layout, assets/models/*_v3)."""
import hashlib
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import lane  # noqa: E402

argv = [a for a in sys.argv[1:] if not a.startswith("--")]
nested = "--nested" in sys.argv[1:]
only = next((a.split("=", 1)[1].split(",") for a in sys.argv[1:] if a.startswith("--only=")), None)
folder, prefix = Path(argv[0]).resolve(), argv[1]
luau_out, table = (Path(argv[2]), argv[3]) if len(argv) > 3 else (None, None)
ids_p = folder / "uploaded.json"
ids = json.loads(ids_p.read_text()) if ids_p.exists() else {}
rel = folder.relative_to(lane.ROOT)
pcdir = f"{lane.PCWIN}\\{str(rel).replace('/', chr(92))}"
lane.ssh(f"cmd /c \"if not exist {pcdir} mkdir {pcdir}\"")
failed = []
for f in sorted(folder.glob("*/*.glb") if nested else folder.glob("*.glb")):
    name = f.stem
    if nested and f.parent.name != name:
        continue  # only <name>/<name>.glb; working files (_in.glb, model_url.glb) stay local
    if only and name not in only:
        continue
    sha = hashlib.sha256(f.read_bytes()).hexdigest()
    if ids.get(name, {}).get("sha256") == sha:
        continue
    lane.put(f, f"{rel}/{f.name}")  # flat on the PC side: <folder>/<name>.glb
    log = lane.ssh(f"powershell -NoProfile -ExecutionPolicy Bypass -File {lane.PCWIN}\\win\\upload_model_skyrally.ps1 "
                   f"-Path {pcdir}\\{f.name} -Name {prefix}{name}", check=False, timeout=1200)
    mid = re.search(r"MODEL_ASSET_ID=(\d+)", log)
    if not (mid and re.search(r"GRANT_STATUS=\d+ ok=True", log)):
        failed.append(name)
        print("FAILED", name, log[-400:], flush=True)
        continue
    ids[name] = {"model": int(mid.group(1)), "sha256": sha, "file": str(f.relative_to(lane.ROOT)), "name": f"{prefix}{name}"}
    ids_p.write_text(json.dumps(ids, indent=1) + "\n")
    print("OK", name, mid.group(1), flush=True)
if luau_out:
    lines = [f"--!strict\n-- Generated by tools/upload_models.py from {rel}/uploaded.json (do not edit by hand).",
             "-- Roblox Model asset ids (each wraps one MeshPart), all with a validated Use grant to the universe.",
             f"local {table}: {{ [string]: number }} = {{"]
    lines += [f"\t{k} = {v['model']}," for k, v in sorted(ids.items())]
    lines += ["}", "", f"return {table}", ""]
    luau_out.write_text("\n".join(lines))
    print("wrote", luau_out)
print("FAILED:", failed if failed else "none")
sys.exit(1 if failed else 0)
