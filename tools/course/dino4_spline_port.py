def cr(p0,p1,p2,p3,t):
    t2=t*t;t3=t2*t
    return 0.5*((2*p1)+(-p0+p2)*t+(2*p0-5*p1+4*p2-p3)*t2+(-p0+3*p1-3*p2+p3)*t3)
def gen(scale,steps=9):
    c=len(N);adj=[np.array(n[0],float)+np.array(n[2],float)*scale for n in N]
    wps=[];L=0
    for i in range(c):
        p0=adj[(i-1)%c];p1=adj[i];p2=adj[(i+1)%c];p3=adj[(i+2)%c]
        b1=N[i][1];b2=N[(i+1)%c][1]
        for s in range(steps):
            t=s/steps;pt=cr(p0,p1,p2,p3,t);bk=b1+(b2-b1)*t
            if wps:L+=np.linalg.norm(pt-wps[-1][0])
            wps.append((pt,bk,L,i))
    L+=np.linalg.norm(wps[0][0]-wps[-1][0]);wps.append((wps[0][0],wps[0][1],L,0))
    return wps,L
