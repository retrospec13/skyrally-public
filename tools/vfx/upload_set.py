#!/usr/bin/env python3
"""Upload every PNG in a folder via win/upload_image_skyrally.ps1 (validated Use grant to the universe, ledger lines),
recording ids in <folder>/uploaded.json, and emit a generated Luau id table.
Usage: upload_set.py <folder> <name_prefix> <luau_out> <TableName> [audio]
Idempotent by sha256. With `audio`, uploads the folder's .ogg files as Audio through win/upload_audio_skyrally.ps1."""
import hashlib
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import lane  # noqa: E402

folder, prefix, luau_out, table = Path(sys.argv[1]), sys.argv[2], Path(sys.argv[3]), sys.argv[4]
audio = len(sys.argv) > 5 and sys.argv[5] == "audio"
script, id_key, pattern = ("upload_audio_skyrally.ps1", "AUDIO_ASSET_ID", "*.ogg") if audio else ("upload_image_skyrally.ps1", "IMAGE_ASSET_ID", "*.png")
ids_p = folder / "uploaded.json"
ids = json.loads(ids_p.read_text()) if ids_p.exists() else {}
rel = folder.resolve().relative_to(lane.ROOT)
lane.ssh(f"cmd /c \"if not exist {lane.PCWIN}\\{str(rel).replace('/', chr(92))} mkdir {lane.PCWIN}\\{str(rel).replace('/', chr(92))}\"")
for f in sorted(folder.glob(pattern)):
    sha = hashlib.sha256(f.read_bytes()).hexdigest()
    name = f.stem
    if ids.get(name, {}).get("sha256") == sha:
        continue
    lane.put(f, f"{rel}/{f.name}")
    pcpath = f"{lane.PCWIN}\\{str(rel).replace('/', chr(92))}\\{f.name}"
    log = lane.ssh(f"powershell -NoProfile -ExecutionPolicy Bypass -File {lane.PCWIN}\\win\\{script} -Path {pcpath} -Name {prefix}{name}",
                   check=False, timeout=600)
    mid = re.search(id_key + r"=(\d+)", log)
    if not (mid and re.search(r"GRANT_STATUS=\d+ ok=True", log)):
        print("FAILED", name, log[-500:])
        continue
    ids[name] = {"id": int(mid.group(1)), "sha256": sha}
    ids_p.write_text(json.dumps(ids, indent=1))
    print("uploaded", name, mid.group(1))
lines = ["--!strict", f"-- GENERATED by tools/vfx/upload_set.py from {rel} (owned {'audio' if audio else 'textures'}; Use granted to universe 0,",
         "-- validated per item). Do not edit by hand.", "return {"]
for name in sorted(ids):
    lines.append(f'\t{name} = "rbxassetid://{ids[name]["id"]}",')
lines.append("}")
luau_out.write_text("\n".join(lines) + "\n")
print(table, "entries:", len(ids))
