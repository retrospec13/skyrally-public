#!/usr/bin/env python3
"""Upload assets/vfx/*.png through win/upload_image_skyrally.ps1 (validated Use grant to the universe, ledger lines)
and write the ids into src/shared/VfxAssets.luau. Idempotent: a texture whose sha256 already has an id is skipped."""
import hashlib
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import lane  # noqa: E402

MAN = lane.ROOT / "assets" / "vfx" / "manifest.json"
IDS = lane.ROOT / "assets" / "vfx" / "uploaded.json"


def main():
    man = json.loads(MAN.read_text())
    ids = json.loads(IDS.read_text()) if IDS.exists() else {}
    for name, m in man.items():
        f = lane.ROOT / m["file"]
        sha = hashlib.sha256(f.read_bytes()).hexdigest()
        if ids.get(name, {}).get("sha256") == sha:
            continue
        lane.ssh(f"cmd /c \"if not exist {lane.PCWIN}\\assets\\vfx mkdir {lane.PCWIN}\\assets\\vfx\"")
        lane.put(f, f"assets/vfx/{f.name}")
        log = lane.ssh(f"powershell -NoProfile -ExecutionPolicy Bypass -File {lane.PCWIN}\\win\\upload_image_skyrally.ps1 "
                       f"-Path {lane.PCWIN}\\assets\\vfx\\{f.name} -Name SkyRally_vfx_{name}", check=False, timeout=600)
        mid = re.search(r"IMAGE_ASSET_ID=(\d+)", log)
        ok = re.search(r"GRANT_STATUS=\d+ ok=True", log)
        if not (mid and ok):
            print("FAILED", name, log[-600:])
            continue
        ids[name] = {"id": int(mid.group(1)), "sha256": sha, "flipbook": m["flipbook"], "tint": m["tint"], "use": m["use"]}
        IDS.write_text(json.dumps(ids, indent=1))
        print("uploaded", name, mid.group(1))
    lines = ["--!strict", "-- GENERATED by tools/vfx/upload_textures.py from assets/vfx (owned procedural textures; Use granted to",
             "-- universe 0, validated per item). Do not edit by hand.", "return {"]
    for name in sorted(ids):
        v = ids[name]
        lines.append(f'\t{name} = {{ id = "rbxassetid://{v["id"]}", flipbook = "{v["flipbook"]}", tint = {str(v["tint"]).lower()} }},')
    lines.append("}")
    (lane.ROOT / "src" / "shared" / "VfxAssets.luau").write_text("\n".join(lines) + "\n")
    print("VfxAssets.luau entries:", len(ids))


if __name__ == "__main__":
    main()
